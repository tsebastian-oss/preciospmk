create table if not exists public.b2b_rate_comparables (
  id bigint generated by default as identity primary key,
  source_record_id text not null unique,
  source text not null,
  source_kind text not null,
  source_url text,
  category text not null default 'courier',
  provider_name text not null,
  provider_group text not null,
  buyer_name text,
  service_type text,
  origin_label text,
  destination_label text,
  weight_kg numeric,
  distance_km numeric,
  shipment_price_clp numeric,
  price_per_kg_clp numeric,
  price_per_km_clp numeric,
  price_per_kg_km_clp numeric,
  weight_band text,
  distance_band text,
  profile_key text not null,
  comparability_level text not null,
  confidence smallint not null default 50 check (confidence between 0 and 100),
  normalization_method text,
  process_date date,
  metadata jsonb,
  ingested_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists b2b_rate_comparables_profile_idx on public.b2b_rate_comparables(category, profile_key, process_date desc);
create index if not exists b2b_rate_comparables_provider_idx on public.b2b_rate_comparables(provider_group, process_date desc);
create index if not exists b2b_rate_comparables_weight_idx on public.b2b_rate_comparables(weight_band, distance_band);

alter table public.b2b_rate_comparables enable row level security;
drop policy if exists b2b_rate_comparables_authenticated_read on public.b2b_rate_comparables;
create policy b2b_rate_comparables_authenticated_read on public.b2b_rate_comparables for select to authenticated using (true);

create or replace function public.b2b_weight_band(p_weight numeric)
returns text language sql immutable as $$
  select case when p_weight is null or p_weight <= 0 then 'Sin peso' when p_weight <= 1 then '0–1 kg' when p_weight <= 3 then '1–3 kg' when p_weight <= 5 then '3–5 kg' when p_weight <= 10 then '5–10 kg' when p_weight <= 20 then '10–20 kg' else '20+ kg' end
$$;

create or replace function public.b2b_distance_band(p_distance numeric)
returns text language sql immutable as $$
  select case when p_distance is null or p_distance <= 0 then 'Sin distancia' when p_distance <= 50 then '0–50 km' when p_distance <= 200 then '50–200 km' when p_distance <= 500 then '200–500 km' when p_distance <= 1000 then '500–1.000 km' else '1.000+ km' end
$$;

create or replace function public.b2b_sync_comparable_from_observation()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_description text := coalesce(new.description,''); v_weight_text text; v_distance_text text;
  v_weight numeric; v_distance numeric; v_price numeric; v_weight_band text; v_distance_band text;
  v_level text; v_confidence smallint; v_profile text; v_aggregate boolean;
begin
  delete from public.b2b_rate_comparables where source_record_id = new.source_record_id;
  if coalesce(new.unit_price_clp,0) <= 0 or new.price_basis <> 'awarded_unit_price' then return new; end if;
  v_aggregate := v_description ~* '(mensual|anual|contrato|factura|facturas|mes de|servicio anual|servicio mensual|monto total|periodo de [0-9]+ meses)';
  if v_aggregate then return new; end if;
  v_weight_text := substring(v_description from '([0-9]+([\.,][0-9]+)?)\s*(kg|kgs|kilo|kilos|kilogramo|kilogramos)');
  v_distance_text := substring(v_description from '([0-9]+([\.,][0-9]+)?)\s*(km|kms|kilometro|kilometros)');
  begin if v_weight_text is not null then v_weight := replace(v_weight_text, ',', '.')::numeric; end if; exception when others then v_weight := null; end;
  begin if v_distance_text is not null then v_distance := replace(v_distance_text, ',', '.')::numeric; end if; exception when others then v_distance := null; end;
  if coalesce(v_weight,0) <= 0 and coalesce(v_distance,0) <= 0 then return new; end if;
  v_price := new.unit_price_clp; v_weight_band := public.b2b_weight_band(v_weight); v_distance_band := public.b2b_distance_band(v_distance);
  v_level := case when v_weight is not null and v_distance is not null then 'full' when v_weight is not null then 'weight' else 'distance' end;
  v_confidence := case when v_level = 'full' then 95 else 80 end;
  v_profile := concat_ws(' | ', coalesce(nullif(new.service_type,''),'Courier'), v_weight_band, v_distance_band);
  insert into public.b2b_rate_comparables (
    source_record_id, source, source_kind, source_url, category, provider_name, provider_group, buyer_name, service_type,
    weight_kg, distance_km, shipment_price_clp, price_per_kg_clp, price_per_km_clp, price_per_kg_km_clp,
    weight_band, distance_band, profile_key, comparability_level, confidence, normalization_method, process_date, metadata, updated_at
  ) values (
    new.source_record_id, new.source, new.source_kind, new.source_url, new.category, new.provider_name, new.provider_group, new.buyer_name, new.service_type,
    v_weight, v_distance, v_price, case when v_weight > 0 then v_price/v_weight else null end,
    case when v_distance > 0 then v_price/v_distance else null end,
    case when v_weight > 0 and v_distance > 0 then v_price/(v_weight*v_distance) else null end,
    v_weight_band, v_distance_band, v_profile, v_level, v_confidence, 'explicit_weight_distance_from_public_line', new.process_date,
    jsonb_build_object('rawObservationId',new.id), now()
  ) on conflict (source_record_id) do update set
    provider_name=excluded.provider_name, provider_group=excluded.provider_group, buyer_name=excluded.buyer_name,
    service_type=excluded.service_type, weight_kg=excluded.weight_kg, distance_km=excluded.distance_km,
    shipment_price_clp=excluded.shipment_price_clp, price_per_kg_clp=excluded.price_per_kg_clp,
    price_per_km_clp=excluded.price_per_km_clp, price_per_kg_km_clp=excluded.price_per_kg_km_clp,
    weight_band=excluded.weight_band, distance_band=excluded.distance_band, profile_key=excluded.profile_key,
    comparability_level=excluded.comparability_level, confidence=excluded.confidence, normalization_method=excluded.normalization_method,
    process_date=excluded.process_date, source_url=excluded.source_url, metadata=excluded.metadata, updated_at=now();
  return new;
end;
$$;

drop trigger if exists trg_b2b_sync_comparable on public.b2b_public_observations;
create trigger trg_b2b_sync_comparable after insert or update of description, unit_price_clp, price_basis, provider_group, service_type, process_date on public.b2b_public_observations for each row execute function public.b2b_sync_comparable_from_observation();

create or replace function public.b2b_upsert_rate_comparables(p_rows jsonb)
returns integer language plpgsql security definer set search_path = public as $$
declare v_count integer := 0;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' then return 0; end if;
  insert into public.b2b_rate_comparables (
    source_record_id, source, source_kind, source_url, category, provider_name, provider_group, buyer_name, service_type,
    origin_label, destination_label, weight_kg, distance_km, shipment_price_clp, price_per_kg_clp, price_per_km_clp,
    price_per_kg_km_clp, weight_band, distance_band, profile_key, comparability_level, confidence, normalization_method,
    process_date, metadata, updated_at
  )
  select x.source_record_id, x.source, x.source_kind, x.source_url, coalesce(nullif(x.category,''),'courier'), x.provider_name, x.provider_group,
    x.buyer_name, x.service_type, x.origin_label, x.destination_label, x.weight_kg, x.distance_km, x.shipment_price_clp,
    case when x.weight_kg > 0 then x.shipment_price_clp/x.weight_kg else null end,
    case when x.distance_km > 0 then x.shipment_price_clp/x.distance_km else null end,
    case when x.weight_kg > 0 and x.distance_km > 0 then x.shipment_price_clp/(x.weight_kg*x.distance_km) else null end,
    public.b2b_weight_band(x.weight_kg), public.b2b_distance_band(x.distance_km),
    concat_ws(' | ',coalesce(nullif(x.service_type,''),'Courier'),public.b2b_weight_band(x.weight_kg),public.b2b_distance_band(x.distance_km)),
    case when x.weight_kg > 0 and x.distance_km > 0 then 'full' when x.weight_kg > 0 then 'weight' when x.distance_km > 0 then 'distance' else 'none' end,
    greatest(0,least(coalesce(x.confidence,80),100))::smallint, coalesce(nullif(x.normalization_method,''),'standardized_rate_card'), x.process_date, x.metadata, now()
  from jsonb_to_recordset(p_rows) as x(source_record_id text,source text,source_kind text,source_url text,category text,provider_name text,provider_group text,buyer_name text,service_type text,origin_label text,destination_label text,weight_kg numeric,distance_km numeric,shipment_price_clp numeric,confidence integer,normalization_method text,process_date date,metadata jsonb)
  where nullif(x.source_record_id,'') is not null and nullif(x.provider_group,'') is not null and x.shipment_price_clp > 0
  on conflict (source_record_id) do update set source=excluded.source,source_kind=excluded.source_kind,source_url=excluded.source_url,provider_name=excluded.provider_name,provider_group=excluded.provider_group,buyer_name=excluded.buyer_name,service_type=excluded.service_type,origin_label=excluded.origin_label,destination_label=excluded.destination_label,weight_kg=excluded.weight_kg,distance_km=excluded.distance_km,shipment_price_clp=excluded.shipment_price_clp,price_per_kg_clp=excluded.price_per_kg_clp,price_per_km_clp=excluded.price_per_km_clp,price_per_kg_km_clp=excluded.price_per_kg_km_clp,weight_band=excluded.weight_band,distance_band=excluded.distance_band,profile_key=excluded.profile_key,comparability_level=excluded.comparability_level,confidence=excluded.confidence,normalization_method=excluded.normalization_method,process_date=excluded.process_date,metadata=excluded.metadata,updated_at=now();
  get diagnostics v_count = row_count; return v_count;
end;
$$;
revoke all on function public.b2b_upsert_rate_comparables(jsonb) from public;
grant execute on function public.b2b_upsert_rate_comparables(jsonb) to authenticated;

create or replace function public.b2b_pricing_comparables(p_category text default 'courier', p_days integer default 365)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_days integer := greatest(30,least(coalesce(p_days,365),1095)); v_result jsonb;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  with filtered as (
    select * from public.b2b_rate_comparables where category=coalesce(nullif(p_category,''),'courier') and coalesce(process_date,ingested_at::date)>=current_date-v_days and shipment_price_clp>0 and comparability_level<>'none'
  ), profile_stats as (
    select profile_key,max(service_type) service_type,max(weight_band) weight_band,max(distance_band) distance_band,count(*) observations,count(distinct provider_group) providers,
      percentile_cont(0.5) within group(order by shipment_price_clp) market_median_shipment_price,
      percentile_cont(0.5) within group(order by price_per_kg_clp) filter(where price_per_kg_clp>0) market_median_price_per_kg,
      percentile_cont(0.5) within group(order by price_per_km_clp) filter(where price_per_km_clp>0) market_median_price_per_km,max(process_date) latest_date
    from filtered group by profile_key
  ), provider_profile as (
    select f.profile_key,max(f.service_type) service_type,max(f.weight_band) weight_band,max(f.distance_band) distance_band,f.provider_group,max(f.provider_name) provider_name,count(*) observations,
      percentile_cont(0.5) within group(order by f.shipment_price_clp) median_shipment_price,
      percentile_cont(0.5) within group(order by f.price_per_kg_clp) filter(where f.price_per_kg_clp>0) median_price_per_kg,
      percentile_cont(0.5) within group(order by f.price_per_km_clp) filter(where f.price_per_km_clp>0) median_price_per_km,
      percentile_cont(0.5) within group(order by f.price_per_kg_km_clp) filter(where f.price_per_kg_km_clp>0) median_price_per_kg_km,
      max(f.process_date) latest_date,round(avg(f.confidence),0) confidence,max(f.origin_label) origin_label,max(f.destination_label) destination_label
    from filtered f group by f.profile_key,f.provider_group
  ), rows as (
    select jsonb_agg(jsonb_build_object('profileKey',pp.profile_key,'serviceType',pp.service_type,'weightBand',pp.weight_band,'distanceBand',pp.distance_band,'providerGroup',pp.provider_group,'providerName',pp.provider_name,'observations',pp.observations,'medianShipmentPrice',pp.median_shipment_price,'medianPricePerKg',pp.median_price_per_kg,'medianPricePerKm',pp.median_price_per_km,'medianPricePerKgKm',pp.median_price_per_kg_km,'marketMedianShipmentPrice',ps.market_median_shipment_price,'marketMedianPricePerKg',ps.market_median_price_per_kg,'marketMedianPricePerKm',ps.market_median_price_per_km,'providersInProfile',ps.providers,'indexVsMarket',case when ps.providers>=2 and ps.market_median_shipment_price>0 then round((pp.median_shipment_price/ps.market_median_shipment_price*100)::numeric,1) else null end,'latestDate',pp.latest_date,'confidence',pp.confidence,'originLabel',pp.origin_label,'destinationLabel',pp.destination_label) order by ps.providers desc,pp.profile_key,pp.median_shipment_price) data
    from provider_profile pp join profile_stats ps using(profile_key)
  ), profiles as (
    select jsonb_agg(jsonb_build_object('profileKey',profile_key,'serviceType',service_type,'weightBand',weight_band,'distanceBand',distance_band,'observations',observations,'providers',providers,'marketMedianShipmentPrice',market_median_shipment_price,'marketMedianPricePerKg',market_median_price_per_kg,'marketMedianPricePerKm',market_median_price_per_km,'latestDate',latest_date) order by providers desc,observations desc) data from profile_stats
  ), summary as (
    select jsonb_build_object('comparableRows',count(*),'fullRows',count(*) filter(where comparability_level='full'),'providers',count(distinct provider_group),'profiles',count(distinct profile_key),'competitiveProfiles',(select count(*) from profile_stats where providers>=2),'latestDate',max(process_date)) data from filtered
  )
  select jsonb_build_object('summary',coalesce((select data from summary),'{}'::jsonb),'profiles',coalesce((select data from profiles),'[]'::jsonb),'rows',coalesce((select data from rows),'[]'::jsonb)) into v_result;
  return v_result;
end;
$$;
revoke all on function public.b2b_pricing_comparables(text,integer) from public;
grant execute on function public.b2b_pricing_comparables(text,integer) to authenticated;

update public.b2b_public_observations set updated_at=updated_at;
