create or replace function public.start_automotive_crawl_service(p_trigger_type text default 'scheduled')
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $function$
declare
  v_local_date date := (now() at time zone 'America/Santiago')::date;
  v_run_id bigint;
  v_tasks integer := 0;
begin
  perform pg_advisory_xact_lock(824632026);

  select id into v_run_id
  from public.catalog_crawl_runs
  where vertical='automotive' and status='running'
  order by started_at desc
  limit 1;
  if v_run_id is not null then
    return jsonb_build_object('started',false,'reason','automotive_run_active','runId',v_run_id);
  end if;

  if p_trigger_type='scheduled' then
    select id into v_run_id
    from public.catalog_crawl_runs
    where vertical='automotive' and run_date=v_local_date and trigger_type='scheduled'
    order by id desc limit 1;
    if v_run_id is not null then
      return jsonb_build_object('started',false,'reason','already_scheduled','runId',v_run_id);
    end if;
  end if;

  insert into public.catalog_crawl_runs(
    status,vertical,trigger_type,run_date,window_end_at,configuration
  ) values (
    'running','automotive',p_trigger_type,v_local_date,now()+interval '20 hours',
    jsonb_build_object('strategy','dealer_first','country','CL','sourcePolicy','dealer_primary_brand_fallback')
  ) returning id into v_run_id;

  insert into public.catalog_crawl_tasks(run_id,task_key,supermarket,vertical,kind,payload,status,available_at)
  select
    v_run_id,
    format('automotive-source:%s',s.source_key),
    s.dealer,
    'automotive',
    'automotive_dealer_catalog',
    jsonb_build_object(
      'source_id',s.id,
      'source_key',s.source_key,
      'parser_key',s.parser_key,
      'url',s.catalog_url,
      'stage','root',
      'crawl_delay_ms',s.crawl_delay_ms
    ),
    'queued',
    now()
  from public.automotive_sources s
  where s.enabled
  order by s.priority,s.id;

  get diagnostics v_tasks = row_count;
  update public.catalog_crawl_runs set tasks_total=v_tasks where id=v_run_id;

  if v_tasks=0 then
    update public.catalog_crawl_runs
    set status='failed',finished_at=now(),completion_reason='no_automotive_sources'
    where id=v_run_id;
  end if;

  return jsonb_build_object('started',v_tasks>0,'runId',v_run_id,'tasks',v_tasks,'runDate',v_local_date);
end;
$function$;

