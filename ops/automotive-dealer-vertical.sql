create or replace function public.start_automotive_crawls_if_due_service()
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $function$
declare
  v_local_ts timestamp := now() at time zone 'America/Santiago';
  v_isodow integer := extract(isodow from (now() at time zone 'America/Santiago'))::integer;
begin
  if v_isodow not in (1,5) then
    return jsonb_build_object('started',false,'reason','not_monday_or_friday','localTime',v_local_ts);
  end if;
  if v_local_ts::time < time '01:30' or v_local_ts::time >= time '02:30' then
    return jsonb_build_object('started',false,'reason','outside_start_window','localTime',v_local_ts);
  end if;
  return public.start_automotive_crawl_service('scheduled');
end;
$function$;

