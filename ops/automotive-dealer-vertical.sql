create or replace function public.finish_automotive_task_service(
  p_task_id bigint,
  p_success boolean,
  p_products_found integer default 0,
  p_error text default null
)
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $function$
declare
  v_run_id bigint;
  v_pending integer;
  v_completed integer;
  v_failed integer;
  v_products integer;
  v_status text;
begin
  update public.catalog_crawl_tasks
  set status=case when p_success then 'completed' else 'failed' end,
      finished_at=now(),claimed_at=null,products_found=greatest(coalesce(p_products_found,0),0),
      error=case when p_success then null else left(coalesce(p_error,'automotive_task_failed'),4000) end
  where id=p_task_id and vertical='automotive'
  returning run_id into v_run_id;
  if v_run_id is null then raise exception 'Automotive task not found'; end if;

  select count(*) filter(where status in('queued','running')),
         count(*) filter(where status='completed'),
         count(*) filter(where status='failed'),
         coalesce(sum(products_found),0)
  into v_pending,v_completed,v_failed,v_products
  from public.catalog_crawl_tasks where run_id=v_run_id;

  v_status:=case when v_pending>0 then 'running' when v_failed>0 then 'completed_with_errors' else 'completed' end;
  update public.catalog_crawl_runs
  set status=v_status,tasks_total=v_pending+v_completed+v_failed,tasks_completed=v_completed,tasks_failed=v_failed,
      products_found=v_products,finished_at=case when v_pending=0 then now() else null end,
      completion_reason=case when v_pending=0 then 'automotive_queue_drained' else null end
  where id=v_run_id;

  return jsonb_build_object('runId',v_run_id,'status',v_status,'pending',v_pending,'completed',v_completed,'failed',v_failed,'products',v_products);
end;
$function$;

